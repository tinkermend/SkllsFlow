export function IconPicker({ value, onChange }: IconPickerProps) {
  const [open, setOpen] = useState(false)

  const handleSelect = (icon: string) => {
    onChange(icon)
    setOpen(false)
  }

  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger asChild>
        <Button
          variant="outline"
          className="w-full justify-start gap-2 h-auto py-2"
        >
          <span className="text-2xl">{value}</span>
          <span className="text-sm text-muted-foreground">点击选择图标</span>
        </Button>
      </PopoverTrigger>
      <PopoverContent className="w-80 p-0" align="start">
        <ScrollArea className="h-[500px] [&_[data-slot=scroll-area-scrollbar]]:w-4">
          <div className="p-3 space-y-4">
            {Object.entries(ICON_CATEGORIES).map(([category, icons]) => (
              <div key={category}>
                <h4 className="text-sm font-semibold mb-2 text-muted-foreground">
                  {category}
                </h4>
                <div className="grid grid-cols-8 gap-2">
                  {icons.map((icon) => (
                    <button
                      key={icon}
                      type="button"
                      onClick={() => handleSelect(icon)}
                      className={`
                        flex items-center justify-center w-10 h-10 text-2xl
                        rounded-md hover:bg-accent transition-colors
                        ${value === icon ? 'bg-accent ring-2 ring-primary' : ''}
                      `}
                    >
                      {icon}
                    </button>
                  ))}
                </div>
              </div>
            ))}
          </div>
        </ScrollArea>
      </PopoverContent>
    </Popover>
  )
}
